export const DEFAULT_NOTE_GENRE: NoteGenreProfile = NOTE_GENRES[NOTE_GENRES.length - 1]!;

/**
 * ニッチ名からジャンルを判定する。どれにも当たらなければ汎用。
 * 判定は**部分一致**で、先に定義されたジャンルが勝つ (`NOTE_GENRES` の順序が優先順位)。
 */
export function classifyNicheGenre(niche: string | null | undefined): NoteGenreProfile {
  const n = (niche ?? '').trim();
  if (n.length === 0) return DEFAULT_NOTE_GENRE;
  for (const g of NOTE_GENRES) {
    if (g.match.some((m) => n.includes(m))) return g;
  }
  return DEFAULT_NOTE_GENRE;
}
